const { app } = require('electron')
const path = require('node:path')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const resultPath = path.resolve(process.env.GEEKGEEKRUN_DATA_DIR, '../package-native-result.json')
app.whenReady().then(async () => {
  const { initDb } = require(path.join(process.env.GEEKGEEKRUN_PACKED_ASAR, 'node_modules/@geekgeekrun/sqlite-plugin/dist/index.js'))
  const ds = await initDb(path.join(process.env.GEEKGEEKRUN_DATA_DIR, 'storage/public.db'))
  const rows = await ds.query('SELECT count(*) AS count FROM chat_startup_log')
  assert.equal(rows[0].count, 906)
  await ds.destroy()
  fs.writeFileSync(resultPath, JSON.stringify({ passed: true, electron: process.versions.electron, chatRecords: rows[0].count, packagedNativeModuleLoads: true }, null, 2))
  app.exit(0)
}).catch(err => { fs.writeFileSync(resultPath, JSON.stringify({ passed: false, error: err.stack }, null, 2)); app.exit(1) })
